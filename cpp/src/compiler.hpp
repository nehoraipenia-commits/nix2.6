// ==============================================================================
// NIX NATIVE COMPILER (C++ Code Generator)
// Generates optimized, standalone native C++ code embedding the runtime,
// compiling Nix code directly into native executables.
// ==============================================================================
#pragma once

#include <string>
#include <sstream>
#include <vector>
#include <unordered_set>
#include <memory>
#include <fstream>
#include <cstdlib>
#include <iostream>

#include "frontend.hpp"

namespace nix {

class Compiler {
public:
    std::string script_dir;

    Compiler() : temp_var_count_(0), indent_level_(0) {}

    std::string generate_cpp(const ProgramNode* prog, const std::string& runtime_header_path = "nix_runtime.hpp", bool embed_full_runtime = false) {
        temp_var_count_ = 0;
        indent_level_ = 0;
        forward_decls_.clear();
        func_defs_.clear();
        main_lines_.clear();
        global_decls_.clear();
        scopes_.clear();
        scopes_.push_back({}); // global scope

        declared_functions_.clear();
        inside_method_ = false;

        // Pre-pass: collect top-level functions, classes, global variables, and `using` imports
        for (const auto& stmt : prog->stmts) {
            if (stmt->kind == NK::FuncDef) {
                declared_functions_.insert(as<FuncDefNode>(stmt.get())->name);
            } else if (stmt->kind == NK::ClassDef) {
                declared_functions_.insert(as<ClassDefNode>(stmt.get())->name);
            } else if (stmt->kind == NK::Assign) {
                auto* a = as<AssignNode>(stmt.get());
                if (a->target->kind == NK::Ident) {
                    std::string vname = sanitize_name(as<IdentNode>(a->target.get())->name);
                    if (!is_declared(vname)) {
                        declare(vname);
                        global_decls_.push_back("Value " + vname + ";");
                    }
                }
            } else if (stmt->kind == NK::Using) {
                auto* un = as<UsingNode>(stmt.get());
                const natives::ModuleDef* m = natives::find_module(un->lib);
                if (m) {
                    for (const auto& c : m->constants) {
                        std::string cname = sanitize_name(c.name);
                        if (!is_declared(cname)) {
                            declare(cname);
                            global_decls_.push_back("Value " + cname + ";");
                        }
                    }
                    for (const auto& f : m->functions) {
                        std::string fname = sanitize_name(f.name);
                        if (!is_declared(fname)) {
                            declare(fname);
                            global_decls_.push_back("Value " + fname + ";");
                        }
                    }
                }
            }
        }

        // Collect statements
        for (const auto& stmt : prog->stmts) {
            if (stmt->kind == NK::FuncDef) {
                gen_func_def(as<FuncDefNode>(stmt.get()));
            } else if (stmt->kind == NK::ClassDef) {
                gen_class_def(as<ClassDefNode>(stmt.get()));
            } else {
                std::string line = gen_statement(stmt.get());
                if (!line.empty()) {
                    main_lines_.push_back(line);
                }
            }
        }

        std::ostringstream out;
        out << "// Auto-generated by Nix Native Compiler\n";
        out << "#include <iostream>\n";
        out << "#include <string>\n";
        out << "#include <vector>\n";
        out << "#include <map>\n";
        out << "#include <cmath>\n";
        out << "#include <stdexcept>\n";
        out << "#include <memory>\n";

        if (embed_full_runtime) {
            std::ifstream rfile(runtime_header_path);
            if (rfile.is_open()) {
                out << rfile.rdbuf() << "\n";
            } else {
                out << "#include \"" << runtime_header_path << "\"\n";
            }
        } else {
            out << "#include \"" << runtime_header_path << "\"\n";
        }

        out << "\nusing namespace nix;\n\n";

        out << "// Global Variables & Imported Symbols\n";
        for (const auto& gdecl : global_decls_) {
            out << gdecl << "\n";
        }
        out << "\n";

        out << "// Forward Declarations\n";
        for (const auto& decl : forward_decls_) {
            out << decl << ";\n";
        }
        out << "\n";

        out << "// Function & Class Definitions\n";
        for (const auto& fdef : func_defs_) {
            out << fdef << "\n\n";
        }

        out << "int main(int argc, char** argv) {\n";
        out << "    for (int i = 1; i < argc; ++i) {\n";
        out << "        program_args().push_back(argv[i]);\n";
        out << "    }\n";
        out << "    try {\n";
        for (const auto& l : main_lines_) {
            out << "        " << l << "\n";
        }
        out << "        qt_gui::auto_exec_if_windows_open();\n";
        out << "    } catch (const TopLevelReturn& ret) {\n";
        out << "        qt_gui::auto_exec_if_windows_open();\n";
        out << "        return 0;\n";
        out << "    } catch (const RuntimeError& ex) {\n";
        out << "        report_runtime_error(ex);\n";
        out << "        return 1;\n";
        out << "    } catch (const std::exception& ex) {\n";
        out << "        report_internal(ex.what());\n";
        out << "        return 1;\n";
        out << "    }\n";
        out << "    return 0;\n";
        out << "}\n";

        return out.str();
    }

private:
    int temp_var_count_;
    int indent_level_;
    std::vector<std::string> forward_decls_;
    std::vector<std::string> func_defs_;
    std::vector<std::string> main_lines_;
    std::vector<std::string> global_decls_;
    std::vector<std::unordered_set<std::string>> scopes_;

    std::unordered_set<std::string> declared_functions_;
    bool inside_method_ = false;

    void enter_scope() { scopes_.push_back({}); }
    void exit_scope() { if (scopes_.size() > 1) scopes_.pop_back(); }
    bool is_declared(const std::string& name) {
        for (auto it = scopes_.rbegin(); it != scopes_.rend(); ++it) {
            if (it->count(name)) return true;
        }
        return false;
    }
    void declare(const std::string& name) {
        scopes_.back().insert(name);
    }

    std::string new_temp(const std::string& prefix = "_t") {
        return prefix + std::to_string(++temp_var_count_);
    }

    std::string sanitize_name(const std::string& name) {
        // Handle C++ reserved keywords if used in Nix
        static const std::unordered_set<std::string> kws = {
            "int", "double", "float", "char", "bool", "void", "auto", "const",
            "class", "struct", "template", "namespace", "return", "if", "else",
            "while", "for", "switch", "case", "default", "break", "continue",
            "delete", "new", "try", "catch", "throw", "this", "friend", "virtual",
            "public", "private", "protected", "static", "register", "volatile"
        };
        if (kws.count(name)) {
            return "_nx_" + name;
        }
        return name;
    }

    void gen_func_def(const FuncDefNode* fn) {
        gen_func_def_with_name(fn, fn->name);
    }

    void gen_func_def_with_name(const FuncDefNode* fn, const std::string& name_override, bool is_method = false) {
        std::string fname = sanitize_name(name_override);
        std::ostringstream sig;
        sig << "Value " << fname << "(const Value* _args, size_t _n, const Value& _self)";
        forward_decls_.push_back(sig.str());

        std::ostringstream body;
        body << sig.str() << " {\n";
        body << "    if (_n != " << fn->params.size() << ") {\n";
        body << "        fail(\"Function '" << name_override << "' expects " << fn->params.size() 
             << " arguments, but received \" + std::to_string(_n));\n";
        body << "    }\n";

        bool old_inside = inside_method_;
        inside_method_ = is_method;
        enter_scope();
        for (size_t i = 0; i < fn->params.size(); ++i) {
            std::string pname = sanitize_name(fn->params[i]);
            declare(pname);
            body << "    Value " << pname << " = _args[" << i << "];\n";
        }

        // Generate function body
        if (fn->body) {
            for (const auto& s : fn->body->stmts) {
                std::string line = gen_statement(s.get());
                if (!line.empty()) {
                    body << "    " << line << "\n";
                }
            }
        }
        body << "    return Value::none();\n";
        body << "}";
        exit_scope();
        inside_method_ = old_inside;

        func_defs_.push_back(body.str());
    }

    void gen_class_def(const ClassDefNode* cls) {
        std::string cname = sanitize_name(cls->name);
        std::ostringstream body_fn_sig;
        body_fn_sig << "void _cls_body_" << cname << "(const Value& _self)";
        forward_decls_.push_back(body_fn_sig.str());

        std::ostringstream factory_sig;
        factory_sig << "Value " << cname << "(const Value* _args, size_t _n, const Value& _self)";
        forward_decls_.push_back(factory_sig.str());

        // Body function
        std::ostringstream body;
        body << body_fn_sig.str() << " {\n";
        enter_scope();
        if (cls->body) {
            for (const auto& s : cls->body->stmts) {
                if (s->kind == NK::Assign) {
                    auto* a = as<AssignNode>(s.get());
                    if (a->target->kind == NK::Ident) {
                        std::string field_name = as<IdentNode>(a->target.get())->name;
                        std::string val_expr = gen_expr(a->value.get());
                        body << "    field_set(_self, intern(\"" << field_name << "\"), " << val_expr << ");\n";
                    }
                } else if (s->kind == NK::FuncDef) {
                    auto* m = as<FuncDefNode>(s.get());
                    std::string mname = cname + "_" + m->name;
                    // Define method as function with custom name
                    gen_func_def_with_name(m, mname, true);
                    body << "    field_set(_self, intern(\"" << m->name << "\"), make_func(\"" 
                         << m->name << "\", " << m->params.size() << ", " << sanitize_name(mname) 
                         << ", nullptr, true, false));\n";
                }
            }
        }
        exit_scope();
        body << "}\n\n";

        // Factory function
        body << factory_sig.str() << " {\n";
        body << "    static Value _cls = make_class(\"" << cls->name << "\", _cls_body_" << cname << ", nullptr);\n";
        body << "    return instantiate(_cls);\n";
        body << "}";

        func_defs_.push_back(body.str());
    }

    std::string gen_statement(const Node* node) {
        if (!node) return "";
        switch (node->kind) {
            case NK::Assign: {
                auto* a = as<AssignNode>(node);
                std::string val_code = gen_expr(a->value.get());
                if (a->target->kind == NK::Ident) {
                    std::string raw_name = as<IdentNode>(a->target.get())->name;
                    std::string vname = sanitize_name(raw_name);
                    if (!is_declared(vname)) {
                        declare(vname);
                        return "Value " + vname + " = " + val_code + ";";
                    } else {
                        return vname + " = " + val_code + ";";
                    }
                } else if (a->target->kind == NK::GetAttr) {
                    auto* ga = as<GetAttrNode>(a->target.get());
                    std::string obj_code = gen_expr(ga->obj.get());
                    return "setattr(" + obj_code + ", intern(\"" + ga->member + "\"), " + val_code + ");";
                } else if (a->target->kind == NK::Subscript) {
                    auto* sub = as<SubscriptNode>(a->target.get());
                    std::string coll_code = gen_expr(sub->coll.get());
                    std::string idx_code = gen_expr(sub->index.get());
                    return "setitem(" + coll_code + ", " + idx_code + ", " + val_code + ");";
                }
                return "";
            }
            case NK::If: {
                auto* in = as<IfNode>(node);
                std::string cond_code = gen_expr(in->cond.get());
                std::ostringstream oss;
                oss << "if (truthy(" << cond_code << ")) {\n";
                enter_scope();
                if (in->then_b) {
                    for (const auto& s : in->then_b->stmts) {
                        std::string l = gen_statement(s.get());
                        if (!l.empty()) oss << "        " << l << "\n";
                    }
                }
                exit_scope();
                oss << "    }";
                if (in->else_b) {
                    oss << " else ";
                    if (in->else_b->kind == NK::If) {
                        oss << gen_statement(in->else_b.get());
                    } else if (in->else_b->kind == NK::Program) {
                        oss << "{\n";
                        enter_scope();
                        for (const auto& s : as<ProgramNode>(in->else_b.get())->stmts) {
                            std::string l = gen_statement(s.get());
                            if (!l.empty()) oss << "        " << l << "\n";
                        }
                        exit_scope();
                        oss << "    }";
                    }
                }
                return oss.str();
            }
            case NK::While: {
                auto* wn = as<WhileNode>(node);
                std::string cond_code = gen_expr(wn->cond.get());
                std::ostringstream oss;
                oss << "while (truthy(" << cond_code << ")) {\n";
                enter_scope();
                if (wn->body) {
                    for (const auto& s : wn->body->stmts) {
                        std::string l = gen_statement(s.get());
                        if (!l.empty()) oss << "        " << l << "\n";
                    }
                }
                exit_scope();
                oss << "    }";
                return oss.str();
            }
            case NK::For: {
                auto* fn = as<ForNode>(node);
                std::string iname = sanitize_name(fn->iter);
                std::string limit_code = gen_expr(fn->limit.get());
                std::string count_var = new_temp("_limit");
                std::ostringstream oss;
                oss << "int64_t " << count_var << " = loop_count(" << limit_code << ");\n";
                oss << "    for (int64_t " << iname << "_i = 0; " << iname << "_i < " << count_var << "; ++" << iname << "_i) {\n";
                enter_scope();
                declare(iname);
                oss << "        Value " << iname << " = Value::integer(" << iname << "_i);\n";
                if (fn->body) {
                    for (const auto& s : fn->body->stmts) {
                        std::string l = gen_statement(s.get());
                        if (!l.empty()) oss << "        " << l << "\n";
                    }
                }
                exit_scope();
                oss << "    }";
                return oss.str();
            }
            case NK::Return: {
                auto* rn = as<ReturnNode>(node);
                if (rn->expr) {
                    return "return " + gen_expr(rn->expr.get()) + ";";
                }
                return "return Value::none();";
            }
            case NK::Out: {
                auto* on = as<OutNode>(node);
                std::ostringstream oss;
                oss << "out({";
                for (size_t i = 0; i < on->args.size(); ++i) {
                    if (i > 0) oss << ", ";
                    oss << gen_expr(on->args[i].get());
                }
                oss << "});";
                return oss.str();
            }
            case NK::Using: {
                auto* un = as<UsingNode>(node);
                std::string lib = un->lib;
                const natives::ModuleDef* m = natives::find_module(lib);
                if (m) {
                    std::ostringstream oss;
                    for (const auto& c : m->constants) {
                        std::string cname = sanitize_name(c.name);
                        oss << cname << " = natives::module_value(\"" << lib << "\", \"" << c.name << "\");\n";
                    }
                    for (const auto& f : m->functions) {
                        std::string fname = sanitize_name(f.name);
                        oss << fname << " = natives::module_value(\"" << lib << "\", \"" << f.name << "\");\n";
                    }
                    return oss.str();
                }
                return "// using <" + lib + ">";
            }
            default: {
                std::string expr_code = gen_expr(node);
                if (!expr_code.empty()) {
                    return expr_code + ";";
                }
                return "";
            }
        }
    }

    std::string gen_expr(const Node* node) {
        if (!node) return "Value::none()";
        switch (node->kind) {
            case NK::Literal: {
                auto* lit = as<LiteralNode>(node);
                const Value& v = lit->value;
                if (v.tag == Tag::None) return "Value::none()";
                if (v.tag == Tag::Bool) return v.b ? "Value::boolean(true)" : "Value::boolean(false)";
                if (v.tag == Tag::Int) return "Value::integer(" + std::to_string(v.i) + "LL)";
                if (v.tag == Tag::Float) {
                    std::ostringstream ss;
                    ss << "Value::number(" << v.d << ")";
                    return ss.str();
                }
                if (v.tag == Tag::Str) {
                    std::string s = as_str(v)->s;
                    std::ostringstream ss;
                    ss << "make_str(\"";
                    for (char c : s) {
                        if (c == '"') ss << "\\\"";
                        else if (c == '\\') ss << "\\\\";
                        else if (c == '\n') ss << "\\n";
                        else if (c == '\r') ss << "\\r";
                        else if (c == '\t') ss << "\\t";
                        else ss << c;
                    }
                    ss << "\")";
                    return ss.str();
                }
                return "Value::none()";
            }
            case NK::Ident: {
                std::string iname = as<IdentNode>(node)->name;
                std::string sname = sanitize_name(iname);
                if (declared_functions_.count(iname)) {
                    // It's a top-level function or class symbol
                    return "make_func(\"" + iname + "\", -1, " + sname + ", nullptr, false, false)";
                }
                if (is_declared(sname)) {
                    return "rd(" + sname + ", \"" + iname + "\")";
                }
                if (inside_method_) {
                    return "field_get(_self, intern(\"" + iname + "\"))";
                }
                return "rd(" + sname + ", \"" + iname + "\")";
            }
            case NK::BinOp: {
                auto* b = as<BinOpNode>(node);
                std::string left = gen_expr(b->left.get());
                std::string right = gen_expr(b->right.get());
                switch (b->op) {
                    case Op::Add: return "add(" + left + ", " + right + ")";
                    case Op::Sub: return "sub(" + left + ", " + right + ")";
                    case Op::Mul: return "mul(" + left + ", " + right + ")";
                    case Op::Div: return "divide(" + left + ", " + right + ")";
                    case Op::Mod: return "mod(" + left + ", " + right + ")";
                    case Op::Eq:  return "eq(" + left + ", " + right + ")";
                    case Op::Ne:  return "ne(" + left + ", " + right + ")";
                    case Op::Lt:  return "lt(" + left + ", " + right + ")";
                    case Op::Gt:  return "gt(" + left + ", " + right + ")";
                    case Op::Le:  return "le(" + left + ", " + right + ")";
                    case Op::Ge:  return "ge(" + left + ", " + right + ")";
                }
                return "Value::none()";
            }
            case NK::Unary: {
                auto* u = as<UnaryNode>(node);
                return "neg(" + gen_expr(u->expr.get()) + ")";
            }
            case NK::Vector: {
                auto* vn = as<VectorNode>(node);
                std::ostringstream oss;
                oss << "make_list({";
                for (size_t i = 0; i < vn->elems.size(); ++i) {
                    if (i > 0) oss << ", ";
                    oss << gen_expr(vn->elems[i].get());
                }
                oss << "})";
                return oss.str();
            }
            case NK::Dict: {
                auto* dn = as<DictNode>(node);
                std::ostringstream oss;
                oss << "make_dict({";
                for (size_t i = 0; i < dn->pairs.size(); ++i) {
                    if (i > 0) oss << ", ";
                    oss << gen_expr(dn->pairs[i].first.get()) << ", " << gen_expr(dn->pairs[i].second.get());
                }
                oss << "})";
                return oss.str();
            }
            case NK::Subscript: {
                auto* sub = as<SubscriptNode>(node);
                return "getitem(" + gen_expr(sub->coll.get()) + ", " + gen_expr(sub->index.get()) + ")";
            }
            case NK::GetAttr: {
                auto* ga = as<GetAttrNode>(node);
                return "getattr(" + gen_expr(ga->obj.get()) + ", intern(\"" + ga->member + "\"))";
            }
            case NK::Cin: {
                auto* cn = as<CinNode>(node);
                if (cn->prompt) {
                    std::string pvar = new_temp("_prompt");
                    return "([&]() { Value " + pvar + " = " + gen_expr(cn->prompt.get()) + "; return cin_read(&" + pvar + "); })()";
                }
                return "cin_read(nullptr)";
            }
            case NK::Call: {
                auto* cn = as<CallNode>(node);
                const Node* tgt = cn->target.get();

                // Method call: obj.method(...)
                if (tgt->kind == NK::GetAttr) {
                    auto* ga = as<GetAttrNode>(tgt);
                    std::string obj_code = gen_expr(ga->obj.get());
                    std::ostringstream oss;
                    oss << "call_method(" << obj_code << ", intern(\"" << ga->member << "\"), {";
                    for (size_t i = 0; i < cn->args.size(); ++i) {
                        if (i > 0) oss << ", ";
                        oss << gen_expr(cn->args[i].get());
                    }
                    oss << "})";
                    return oss.str();
                }

                // Known direct function or variable call
                if (tgt->kind == NK::Ident) {
                    std::string fn_name = as<IdentNode>(tgt)->name;
                    std::string san_fn = sanitize_name(fn_name);
                    if (declared_functions_.count(fn_name)) {
                        std::ostringstream oss;
                        oss << "([&]() {\n";
                        oss << "        Value _args_arr[] = {";
                        if (cn->args.empty()) oss << "Value::none()";
                        for (size_t i = 0; i < cn->args.size(); ++i) {
                            if (i > 0) oss << ", ";
                            oss << gen_expr(cn->args[i].get());
                        }
                        oss << "};\n";
                        oss << "        return " << san_fn << "(_args_arr, " << cn->args.size() << ", Value::none());\n";
                        oss << "    })()";
                        return oss.str();
                    }
                }

                std::ostringstream oss;
                oss << "callv(" << gen_expr(tgt) << ", {";
                for (size_t i = 0; i < cn->args.size(); ++i) {
                    if (i > 0) oss << ", ";
                    oss << gen_expr(cn->args[i].get());
                }
                oss << "})";
                return oss.str();
            }
            default:
                return "Value::none()";
        }
    }
};

} // namespace nix
